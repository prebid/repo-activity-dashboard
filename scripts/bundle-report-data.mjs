import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import { resolve, relative, sep } from 'node:path';
import { pathToFileURL } from 'node:url';

export async function bundleReports() {
  const root = resolve('report-data');
  const files = Object.create(null);
  async function visit(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const path = resolve(directory, entry.name);
      if (entry.isSymbolicLink()) throw new Error('Report bundle must not contain symlinks');
      if (entry.isDirectory()) await visit(path);
      else if (entry.isFile() && /\.(json|csv)$/.test(entry.name))
        files[relative(root, path).split(sep).join('/')] = await readFile(path, 'utf8');
    }
  }
  await visit(root);
  const timeline = await readFile('contributor-repo-timeline.json', 'utf8');
  if (!JSON.parse(timeline).data || !JSON.parse(files['sheets/github-mapping.json']).mapping) throw new Error('Missing report data');
  await mkdir('src/generated', { recursive: true });
  await writeFile('src/generated/private-report-data.js',
    '// Generated by scripts/bundle-report-data.mjs. Server code only.\nimport "server-only";\n' +
    '/** @type {Readonly<Record<string, string>>} */\nexport const reportFiles = Object.freeze(JSON.parse(' + JSON.stringify(JSON.stringify(files)) + '));\n' +
    'export const timelineText = ' + JSON.stringify(timeline) + ';\n');
  console.log('Bundled ' + Object.keys(files).length + ' private report files into server-only code.');
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) await bundleReports();
